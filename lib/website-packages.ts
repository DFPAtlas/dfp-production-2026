export const VALID_PACKAGE_IDS = Object.keys(ALL_PACKAGES) as Array<'launch' | 'growth' | 'commerce'>;

export function getPackageById(id: string): WebsitePackage | null {
  const pkg = ALL_PACKAGES[id];
  if (!pkg || !pkg.active) return null;
  return pkg;
}

export function isValidPackageId(id: string): id is keyof typeof ALL_PACKAGES {
  const pkg = ALL_PACKAGES[id];
  return Boolean(pkg && pkg.active);
}

export function formatPriceMinor(minor: number): string {
  return `\u00A3${(minor / 100).toFixed(2)}`;
}

export function formatPriceShortMinor(minor: number): string {
  const pounds = minor / 100;
  if (pounds === Math.floor(pounds)) {
    return `\u00A3${pounds.toLocaleString()}`;
  }
  return `\u00A3${pounds.toFixed(2)}`;
}

export function verifyMilestoneTotals(): { packageId: string; valid: boolean; total: number; expected: number }[] {
  return VALID_PACKAGE_IDS.map((id) => {
    const pkg = ALL_PACKAGES[id];
    const total = pkg.depositMinor + pkg.secondMilestoneMinor + pkg.finalMilestoneMinor;
    return {
      packageId: id,
      valid: total === pkg.fullPriceMinor,
      total,
      expected: pkg.fullPriceMinor,
    };
  });
}